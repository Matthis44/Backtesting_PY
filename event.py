# event.py
from __future__ import print_function
from abc import ABC, abstractmethod


class Event(ABC):
    """
    Base class for all event types in the trading system.
    """

    def to_dict(self):
        return self.__dict__

    @abstractmethod
    def __repr__(self):
        pass


class MarketEvent(Event):
    """
    Event triggered on each new market data "heartbeat".
    """

    def __init__(self):
        self.type = 'MARKET'

    def __repr__(self):
        return f"MarketEvent()"


class SignalEvent(Event):
    """
    Event generated by a Strategy object to signal a trading opportunity.
    """

    def __init__(self, strategy_id, symbol, datetime, signal_type, strength):
        self.type = 'SIGNAL'
        self.strategy_id = strategy_id
        self.symbol = symbol
        self.datetime = datetime
        self.signal_type = signal_type  # 'LONG' or 'SHORT'
        self.strength = strength        # Used to scale order size

    def __repr__(self):
        return (f"SignalEvent(strategy_id={self.strategy_id}, symbol={self.symbol}, "
                f"datetime={self.datetime}, type={self.signal_type}, strength={self.strength})")


class OrderEvent(Event):
    """
    Event to send an order to the execution system.
    """

    def __init__(self, symbol, order_type, quantity, direction):
        self.type = 'ORDER'
        self.symbol = symbol
        self.order_type = order_type  # 'MKT' or 'LMT'
        self.quantity = quantity
        self.direction = direction    # 'BUY' or 'SELL'

    def print_order(self):
        print(self)

    def __repr__(self):
        return (f"OrderEvent(symbol={self.symbol}, type={self.order_type}, "
                f"quantity={self.quantity}, direction={self.direction})")


class CommissionModel(ABC):
    """
    Abstract base class for commission models.
    """
    @abstractmethod
    def calculate(self, quantity):
        pass


class IBCommissionModel(CommissionModel):
    """
    Interactive Brokers commission model.
    """

    def calculate(self, quantity):
        if quantity <= 500:
            return max(1.3, 0.013 * quantity)
        else:
            return max(1.3, 0.008 * quantity)


class FillEvent(Event):
    """
    Event to signal that an order has been fully or partially filled.
    """

    def __init__(self, timeindex, symbol, exchange, quantity, direction,
                 fill_cost, commission=None, commission_model=None):
        self.type = 'FILL'
        self.timeindex = timeindex
        self.symbol = symbol
        self.exchange = exchange
        self.quantity = quantity
        self.direction = direction    # 'BUY' or 'SELL'
        self.fill_cost = fill_cost

        if commission is not None:
            self.commission = commission
        elif commission_model is not None:
            self.commission = commission_model.calculate(quantity)
        else:
            self.commission = IBCommissionModel().calculate(quantity)

    def __repr__(self):
        return (f"FillEvent(timeindex={self.timeindex}, symbol={self.symbol}, exchange={self.exchange}, "
                f"quantity={self.quantity}, direction={self.direction}, "
                f"fill_cost={self.fill_cost:.2f}, commission={self.commission:.2f})")
